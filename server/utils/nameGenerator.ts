// 上の句・下の句それぞれが一度しか使われないよう独立して管理
const usedKamiku = new Set<string>();
const usedShimoku = new Set<string>();

export function suggestPlayerName(): string {
  let availableK = KAMIKU.filter(k => !usedKamiku.has(k));
  let availableS = SHIMOKU.filter(s => !usedShimoku.has(s));

  // どちらかが尽きたら両方リセット
  if (availableK.length === 0 || availableS.length === 0) {
    usedKamiku.clear();
    usedShimoku.clear();
    availableK = [...KAMIKU];
    availableS = [...SHIMOKU];
  }

  const k = availableK[Math.floor(Math.random() * availableK.length)];
  const s = availableS[Math.floor(Math.random() * availableS.length)];

  usedKamiku.add(k);
  usedShimoku.add(s);
  return k + s;
}
